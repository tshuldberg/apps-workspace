/**
 * Category-filtered search for the picker (T1.5). An empty query returns the
 * whole catalog untouched; otherwise a case-insensitive match on the entry name
 * or any keyword keeps the entry, and categories with no surviving entry are
 * dropped. Pure and deterministic.
 */
export function searchEmojiCatalog(
  catalog: readonly EmojiCategory[],
  query: string,
): EmojiCategory[] {
  const q = query.trim().toLowerCase();
  // Fresh array (not the shared readonly alias) so a caller can never mutate the
  // module-level catalog through the returned value.
  if (q === '') return [...catalog];
  const out: EmojiCategory[] = [];
  for (const category of catalog) {
    const matches = category.emoji.filter((entry) =>
      entry.name.toLowerCase().includes(q)
      || entry.keywords.some((keyword) => keyword.toLowerCase().includes(q)),
    );
    if (matches.length > 0) out.push({ ...category, emoji: matches });
  }
  return out;
}
