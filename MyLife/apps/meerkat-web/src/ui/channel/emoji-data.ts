// Plan 30 T1.1: the reaction quick set + the full emoji catalog.
//
// Plain static data, zero native dependency, so it works identically in Expo Go,
// a dev build, Hermes, and Node tests. The protocol accepts any single grapheme
// (see @mylife/sync isSingleEmojiGrapheme), so tuning QUICK_REACTIONS is a pure
// copy change with no schema impact. The catalog is a curated list of common
// emoji grouped by category, each with search keywords for the picker.

/** One catalog entry: the grapheme plus a searchable name and keywords. */
export interface EmojiEntry {
  char: string;
  name: string;
  keywords: string[];
}

/** A named group of emoji rendered as one section in the picker. */
export interface EmojiCategory {
  id: string;
  label: string;
  emoji: EmojiEntry[];
}

/**
 * The six quick reactions (founder decision 2026-07-01), in exact order:
 * heart, thumbs up, laugh, wow, sad, party. Locked by the kit-core unit test.
 */
export const QUICK_REACTIONS: readonly string[] = ['❤️', '👍', '😂', '😮', '😢', '🎉'];

function e(char: string, name: string, ...keywords: string[]): EmojiEntry {
  return { char, name, keywords };
}

