#!/usr/bin/env node
/**
 * Compliance-critical i18n key generator (plan 33 Phase 3.7).
 *
 * A locale must not be presented as "complete" while its SAFETY surface
 * (reporting, appeals, blocking, age gate, account deletion, legal links)
 * still falls back to English. This script extracts every t()/tp() key
 * from the designated safety-surface files, merges the curated settings
 * keys (settings.tsx is too broad to extract wholesale), validates them
 * against the EN catalog, and writes app/(root)/i18n/compliance-keys.ts.
 *
 * Modes:
 *   node scripts/gen-compliance-keys.mjs           # regenerate the module
 *   node scripts/gen-compliance-keys.mjs --check   # fail if committed file is stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const APP = join(__dirname, '..', 'app', '(root)');
const OUT = join(APP, 'i18n', 'compliance-keys.ts');

const SAFETY_FILES = [
  join(APP, 'components', 'ReportMenu.tsx'),
  join(APP, 'my-reports.tsx'),
  join(APP, 'components', 'chef', 'ChefModerationRow.tsx'),
  join(APP, 'i18n', 'LanguageOnboardingGate.tsx'),
];

// Safety/legal strings living in broader screens. Each entry is validated
// to exist in EN AND to be used in its source file (typo defense).
const EXTRA_SOURCES = [
  [join(APP, '(tabs)', 'settings.tsx'), [
    'Delete all data?',
    'Delete',
    'Delete Account',
    'Account deleted',
    'Your BestChef data on this device has been wiped.',
    'We sent recovery instructions for your BestChef account.',
    'Recovery Email',
    'Privacy Policy',
    'Terms of Service',
    'Community Guidelines',
  ]],
  // Reporting entry points that live in broad content screens.
  [join(APP, 'comments', '[submissionId].tsx'), [
    'Report comment',
  ]],
];

const EXTRA_KEYS = EXTRA_SOURCES.flatMap(([, keys]) => keys);

// t('...'), t("..."), tp(n, '...', '...') - captures each quoted key arg.
const CALL_RE = /\btp?\(\s*(?:[^,()]+,\s*)?'((?:[^'\\]|\\.)+)'(?:\s*,\s*'((?:[^'\\]|\\.)+)')?/g;
const CALL_RE_DQ = /\btp?\(\s*(?:[^,()]+,\s*)?"((?:[^"\\]|\\.)+)"/g;

function unescape(raw) {
  return raw
    .replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(Number.parseInt(hex, 16)))
    .replace(/\\(['"\\])/g, '$1');
}

function extractCallKeys(source) {
  const keys = new Set();
  for (const re of [CALL_RE, CALL_RE_DQ]) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(source)) !== null) {
      if (m[1]) keys.add(unescape(m[1]));
      if (m[2]) keys.add(unescape(m[2]));
    }
  }
  return keys;
}

// EN catalog keys, quote/escape agnostic (same contract as check-i18n-parity).
function enKeys() {
  const source = readFileSync(join(APP, 'i18n', 'catalogs', 'en.ts'), 'utf8');
  const keys = new Set();
  const re = /^\s+(?:'((?:[^'\\]|\\.)+)'|"((?:[^"\\]|\\.)+)"|([A-Za-z_][\w-]*)):\s/gm;
  let m;
  while ((m = re.exec(source)) !== null) {
    const raw = m[1] ?? m[2] ?? m[3];
    keys.add(m[3] !== undefined ? raw : unescape(raw));
  }
  return keys;
}

const en = enKeys();
const collected = new Set(EXTRA_KEYS);
for (const file of SAFETY_FILES) {
  for (const key of extractCallKeys(readFileSync(file, 'utf8'))) {
    collected.add(key);
  }
}

for (const [file, keys] of EXTRA_SOURCES) {
  const source = readFileSync(file, 'utf8');
  for (const key of keys) {
    const escaped = key.replace(/'/g, "\\'");
    if (!source.includes(`'${escaped}'`) && !source.includes(JSON.stringify(key))) {
      console.error(`gen-compliance-keys: curated key not used in ${file}: ${JSON.stringify(key)}`);
      process.exit(1);
    }
  }
}

const missing = [...collected].filter((k) => !en.has(k));
if (missing.length > 0) {
  console.error('gen-compliance-keys: keys not present in EN catalog:');
  for (const k of missing) console.error(`  ${JSON.stringify(k)}`);
  process.exit(1);
}

// Plain code-point sort: localeCompare collation can drift across ICU builds
// and spuriously fail the byte-compare in --check.
const sorted = [...collected].sort();
const body = sorted
  .map((k) => `  ${JSON.stringify(k)},`)
  .join('\n');
const content = `/**
 * GENERATED by scripts/gen-compliance-keys.mjs - do not edit by hand.
 * Safety-surface i18n keys (reporting, appeals, blocking, age gate,
 * account deletion, legal links). A locale with ANY of these untranslated
 * is presented as partial regardless of overall completeness
 * (plan 33 Phase 3.7). Regenerate: node scripts/gen-compliance-keys.mjs
 */

export const COMPLIANCE_CRITICAL_KEYS: readonly string[] = [
${body}
];
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    console.error('compliance-keys gate: generated module missing. Run: node apps/bestchef/scripts/gen-compliance-keys.mjs');
    process.exit(1);
  }
  if (current !== content) {
    console.error('compliance-keys gate: STALE. Safety-surface keys changed; regenerate with: node apps/bestchef/scripts/gen-compliance-keys.mjs');
    process.exit(1);
  }
  console.log(`compliance-keys gate: current (${sorted.length} keys).`);
} else {
  writeFileSync(OUT, content);
  console.log(`compliance-keys.ts written (${sorted.length} keys).`);
}
